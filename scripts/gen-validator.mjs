// Precompiles the vendored report schema into a standalone validator so the page needs no
// runtime code generation and can keep a CSP without 'unsafe-eval'.
// Usage: node scripts/gen-validator.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schema = JSON.parse(readFileSync("vendor/eventparity-engine/report.v1.schema.json", "utf8"));
const ajv = new Ajv2020({ strict: false, validateFormats: false, allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
const code = "// @ts-nocheck\n// Generated by scripts/gen-validator.mjs from vendor/eventparity-engine/report.v1.schema.json. Do not edit.\n" + standaloneCode(ajv, validate);
const out = "src/generated/validateReport.js";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== code) {
    console.error(`${out} is out of date; run pnpm gen`);
    process.exit(1);
  }
} else {
  writeFileSync(out, code);
  console.log(`wrote ${out}`);
}
